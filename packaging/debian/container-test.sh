#!/usr/bin/env bash
# Installs a built .deb into a throwaway systemd container and checks the
# packaging contract: user/group, file modes, no secret in the package,
# service start/stop, state kept on remove, everything but the user purged.
#
#   packaging/debian/container-test.sh [debian:12|debian:13] [deb-file]
#
# The .deb must be built for the same suite: the dependency set ($auto) is
# resolved at build time, so a trixie build needs libc6 >= 2.39 and cannot be
# installed on bookworm. Docker is required on the host.
set -euo pipefail

suite=${1:-debian:12}
deb=${2:-target/debian/ferrentd_0.1.0-1_amd64.deb}
case "$suite" in
    ubuntu:*) base="$suite" ;; # Ubuntu has no -slim tags
    *) base="$suite-slim" ;;
esac
image="ferrent-pkgtest:${suite/:/}"
name="ferrent-pkgtest-${suite/:/}"
work=$(mktemp -d)
trap 'docker rm -f "$name" >/dev/null 2>&1 || true; rm -rf "$work"' EXIT

[ -f "$deb" ] || { echo "missing $deb" >&2; exit 1; }

fail=0
note() { printf '%s  %s\n' "$1" "$2"; [ "$1" = FAIL ] && fail=1 || true; }
expect() { # desc expected actual
    if [ "$2" = "$3" ]; then note PASS "$1"; else note FAIL "$1 (expected '$2', got '$3')"; fi
}

# The package must not carry the token; it is generated by postinst.
if dpkg-deb -c "$deb" | grep -q 'etc/ferrent/token'; then
    note FAIL "no token in the package"
else
    note PASS "no token in the package"
fi
if dpkg-deb -c "$deb" | grep -q 'etc/ferrent/config.toml'; then
    note PASS "config.toml shipped as a conffile"
else
    note FAIL "config.toml shipped as a conffile"
fi
if dpkg-deb -c "$deb" | grep -q 'man1/ferrentd.1.gz'; then
    note PASS "man page shipped"
else
    note FAIL "man page shipped"
fi
if dpkg-deb -c "$deb" | grep -q 'systemd/system/ferrentd.service'; then
    note PASS "systemd unit shipped"
else
    note FAIL "systemd unit shipped"
fi

cp "$deb" "$work/package.deb"
cat > "$work/Dockerfile" <<EOF
FROM $base
RUN apt-get update \\
 && apt-get install -y --no-install-recommends systemd systemd-sysv dbus \\
      init-system-helpers adduser procps iproute2 \\
 && rm -rf /var/lib/apt/lists/*
COPY package.deb /tmp/
RUN apt-get update \\
 && apt-get install -y /tmp/package.deb \\
 && rm -f /tmp/package.deb && rm -rf /var/lib/apt/lists/*
# debian:* images ship a policy-rc.d that vetoes service start/stop.
RUN rm -f /usr/sbin/policy-rc.d
STOPSIGNAL SIGRTMIN+3
CMD ["/sbin/init"]
EOF

echo "== building $image from $deb"
docker build -q -f "$work/Dockerfile" -t "$image" "$work" >/dev/null
docker rm -f "$name" >/dev/null 2>&1 || true
docker run -d --name "$name" --privileged --cgroupns=host \
    --tmpfs /run --tmpfs /run/lock \
    -v /sys/fs/cgroup:/sys/fs/cgroup:rw "$image" >/dev/null
for _ in $(seq 30); do
    docker exec "$name" systemctl is-active multi-user.target >/dev/null 2>&1 && break
    sleep 1
done
docker cp "$deb" "$name:/root/package.deb" >/dev/null
if dpkg-deb -f "$deb" Depends | grep -q libtorrent; then static_pkg=0; else static_pkg=1; fi

docker exec -i -e STATIC_PKG="$static_pkg" "$name" bash -s <<'EOS' || fail=1
set -uo pipefail
expect() { if [ "$2" = "$3" ]; then echo "PASS  $1"; else echo "FAIL  $1 (expected '$2', got '$3')"; exit_code=1; fi; }
exit_code=0

expect "systemd reached multi-user" active "$(systemctl is-active multi-user.target)"
expect "ferrent user" ferrent "$(getent passwd ferrent | cut -d: -f1)"
expect "ferrent is a system user" /usr/sbin/nologin "$(getent passwd ferrent | cut -d: -f7)"
expect "ferrent group" ferrent "$(getent group ferrent | cut -d: -f1)"
expect "state dir owner/mode" "ferrent:ferrent 750" "$(stat -c '%U:%G %a' /var/lib/ferrent)"
expect "config owner/mode" "root:ferrent 640" "$(stat -c '%U:%G %a' /etc/ferrent/config.toml)"
expect "token owner/mode" "root:ferrent 640" "$(stat -c '%U:%G %a' /etc/ferrent/token)"
expect "token is a 32-byte base64 secret" 44 "$(tr -d '\n' < /etc/ferrent/token | wc -c)"
expect "unit file installed" yes \
    "$([ -f "$(systemctl show -p FragmentPath --value ferrentd)" ] && echo yes || echo no)"

# The image build installs without systemd running, so postinst skips enabling.
# Reinstall here to exercise the real fresh-install path.
systemctl disable ferrentd >/dev/null 2>&1
apt-get install -y --reinstall /root/package.deb >/dev/null 2>&1
expect "postinst enables the unit" enabled "$(systemctl is-enabled ferrentd)"

systemctl start ferrentd
sleep 3
expect "service active" active "$(systemctl is-active ferrentd)"
expect "listens on 50051" yes "$(ss -ltn | grep -q ':50051 ' && echo yes || echo no)"
if [ "${STATIC_PKG:-0}" = 1 ]; then
    expect "no libtorrent runtime dependency" 0 "$(ldd /usr/bin/ferrentd | grep -c torrent || true)"
fi
expect "startup log line" yes \
    "$(journalctl -u ferrentd --no-pager --since '-1min' | grep -q 'ferrentd listening on' && echo yes || echo no)"

pid_before=$(systemctl show -p MainPID --value ferrentd)
systemctl restart ferrentd
sleep 3
expect "restart yields a new pid" "changed" \
    "$([ "$(systemctl show -p MainPID --value ferrentd)" != "$pid_before" ] && echo changed || echo same)"
expect "TLS cert persisted" yes "$([ -s /var/lib/ferrent/tls-cert.pem ] && echo yes || echo no)"

systemctl stop ferrentd
expect "service stopped" inactive "$(systemctl is-active ferrentd)"
expect "fastresume saved on stop" yes \
    "$(journalctl -u ferrentd --no-pager --since '-1min' | grep -q 'saved fastresume' && echo yes || echo no)"

echo "== remove keeps state"
apt-get remove -y ferrentd >/dev/null 2>&1
expect "remove: binary gone" no "$([ -e /usr/bin/ferrentd ] && echo yes || echo no)"
expect "remove: unit gone" no "$([ -e /usr/lib/systemd/system/ferrentd.service ] && echo yes || echo no)"
expect "remove: state kept" yes "$([ -s /var/lib/ferrent/state.redb ] && echo yes || echo no)"
expect "remove: config kept" yes "$([ -s /etc/ferrent/config.toml ] && echo yes || echo no)"
expect "remove: token kept" yes "$([ -s /etc/ferrent/token ] && echo yes || echo no)"
expect "remove: service stopped" inactive "$(systemctl is-active ferrentd 2>/dev/null || true)"

echo "== purge removes everything but the user"
apt-get install -y /root/package.deb >/dev/null 2>&1
systemctl start ferrentd
sleep 2
apt-get purge -y ferrentd >/dev/null 2>&1
expect "purge: state gone" no "$([ -e /var/lib/ferrent ] && echo yes || echo no)"
expect "purge: config gone" no "$([ -e /etc/ferrent/config.toml ] && echo yes || echo no)"
expect "purge: token gone" no "$([ -e /etc/ferrent/token ] && echo yes || echo no)"
expect "purge: user kept" ferrent "$(getent passwd ferrent | cut -d: -f1)"

exit $exit_code
EOS

echo
if [ "$fail" -eq 0 ]; then echo "== packaging checks: PASS ($suite)"; else echo "== packaging checks: FAIL ($suite)"; fi
exit "$fail"
